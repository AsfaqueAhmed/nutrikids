import { INestApplication } from '@nestjs/common';
import request from 'supertest';
import { PrismaService } from '../src/prisma/prisma.service';
import { createTestApp, registerAndLogin, resetDb } from './helpers';

describe('vaccination', () => {
  let app: INestApplication;
  let prisma: PrismaService;
  const http = () => request(app.getHttpServer());
  beforeAll(async () => {
    app = await createTestApp();
    prisma = app.get(PrismaService);
  });
  beforeEach(() => resetDb(prisma));
  afterAll(() => app.close());

  async function seedVaccines() {
    await prisma.vaccine.create({
      data: {
        code: 'BCG',
        name: 'BCG',
        disease: 'TB',
        description: 'd',
        availability: 'GOVERNMENT_FREE',
        isMandatory: true,
        sourceNote: 'test',
        schedule: {
          create: [
            {
              doseNumber: 1,
              suggestedAgeDays: 0,
              minAgeDays: 0,
              maxAgeDays: 365,
            },
          ],
        },
      },
    });
    await prisma.vaccine.create({
      data: {
        code: 'TCV',
        name: 'Typhoid conjugate',
        disease: 'Typhoid',
        description: 'd',
        availability: 'PRIVATE_PAID',
        priceMinBdt: 1000,
        priceMaxBdt: 2500,
        priceNote: 'per dose',
        sourceNote: 'test',
        schedule: {
          create: [
            {
              doseNumber: 1,
              suggestedAgeDays: 270,
              minAgeDays: 270,
              maxAgeDays: null,
            },
          ],
        },
      },
    });
  }

  async function childWithSchedule(dob: string) {
    const p = await registerAndLogin(app);
    const auth = { Authorization: `Bearer ${p.token}` };
    const child = (
      await http()
        .post('/v1/children')
        .set(auth)
        .send({ name: 'Amina', dateOfBirth: dob, gender: 'FEMALE' })
    ).body;
    // the schedule is generated by an async event; wait for it
    for (
      let i = 0;
      i < 20 &&
      (await prisma.childVaccination.count({ where: { childId: child.id } })) <
        2;
      i++
    )
      await new Promise((r) => setTimeout(r, 50));
    return { auth, child };
  }

  it('generates a schedule when a child is created, with free/paid info', async () => {
    await seedVaccines();
    const { auth, child } = await childWithSchedule('2026-01-01');
    const list = await http()
      .get(`/v1/children/${child.id}/vaccinations`)
      .set(auth)
      .expect(200);
    expect(list.body).toHaveLength(2);
    const bcg = list.body.find((v: any) => v.vaccine.code === 'BCG');
    const tcv = list.body.find((v: any) => v.vaccine.code === 'TCV');
    expect(bcg.vaccine.availability).toBe('GOVERNMENT_FREE');
    expect(tcv.vaccine).toMatchObject({
      availability: 'PRIVATE_PAID',
      priceMinBdt: 1000,
      priceMaxBdt: 2500,
    });
    expect(bcg.dueDate).toBe('2026-01-01');
    expect(tcv.dueDate).toBe('2026-09-28');
  });

  it('marks a dose given, then undone, and tracks the summary', async () => {
    await seedVaccines();
    const { auth, child } = await childWithSchedule('2026-01-01');
    const bcg = (
      await http().get(`/v1/children/${child.id}/vaccinations`).set(auth)
    ).body.find((v: any) => v.vaccine.code === 'BCG');
    const given = await http()
      .put(`/v1/children/${child.id}/vaccinations/${bcg.id}`)
      .set(auth)
      .send({
        givenDate: '2026-01-02',
        facilityName: 'Upazila Health Complex',
        paidType: 'GOVERNMENT',
        clientUpdatedAt: '2026-01-02T10:00:00Z',
      })
      .expect(200);
    expect(given.body.data.status).toBe('GIVEN');
    let summary = (
      await http()
        .get(`/v1/children/${child.id}/vaccinations/summary`)
        .set(auth)
    ).body;
    expect(summary.given).toBe(1);
    await http()
      .put(`/v1/children/${child.id}/vaccinations/${bcg.id}`)
      .set(auth)
      .send({ givenDate: null, clientUpdatedAt: '2026-01-03T10:00:00Z' })
      .expect(200);
    summary = (
      await http()
        .get(`/v1/children/${child.id}/vaccinations/summary`)
        .set(auth)
    ).body;
    expect(summary.given).toBe(0);
  });

  it('rejects a given date before birth and ignores stale writes', async () => {
    await seedVaccines();
    const { auth, child } = await childWithSchedule('2026-01-01');
    const bcg = (
      await http().get(`/v1/children/${child.id}/vaccinations`).set(auth)
    ).body.find((v: any) => v.vaccine.code === 'BCG');
    const url = `/v1/children/${child.id}/vaccinations/${bcg.id}`;
    await http()
      .put(url)
      .set(auth)
      .send({
        givenDate: '2025-12-01',
        clientUpdatedAt: '2026-01-02T10:00:00Z',
      })
      .expect(400);
    await http()
      .put(url)
      .set(auth)
      .send({
        givenDate: '2026-01-02',
        clientUpdatedAt: '2026-01-02T10:00:00Z',
      })
      .expect(200);
    const stale = await http()
      .put(url)
      .set(auth)
      .send({ givenDate: null, clientUpdatedAt: '2026-01-01T10:00:00Z' })
      .expect(200);
    expect(stale.body.sync.superseded).toBe(true);
    expect(stale.body.data.givenDate).toBe('2026-01-02');
  });

  it('re-dates ungiven doses when the date of birth changes', async () => {
    await seedVaccines();
    const { auth, child } = await childWithSchedule('2026-01-01');
    await http()
      .patch(`/v1/children/${child.id}`)
      .set(auth)
      .send({ dateOfBirth: '2026-02-01' })
      .expect(200);
    await new Promise((r) => setTimeout(r, 200));
    const tcv = (
      await http().get(`/v1/children/${child.id}/vaccinations`).set(auth)
    ).body.find((v: any) => v.vaccine.code === 'TCV');
    expect(tcv.dueDate).toBe('2026-10-29');
  });

  it("hides another parent's vaccinations", async () => {
    await seedVaccines();
    const { child } = await childWithSchedule('2026-01-01');
    const other = await registerAndLogin(app, 'other@example.com');
    await http()
      .get(`/v1/children/${child.id}/vaccinations`)
      .set('Authorization', `Bearer ${other.token}`)
      .expect(404);
  });
});
